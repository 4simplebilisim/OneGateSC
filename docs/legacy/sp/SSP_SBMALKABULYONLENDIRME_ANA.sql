
CREATE PROC [dbo].[SSP_SBMALKABULYONLENDIRME_ANA]

(  
 @LNGLOKASYON INT,  
 @LNGKAYNAKLOKASYON int,
 @LNGMALZEME INT,  
 @TXTKONTROLSAHASI NVARCHAR(50),  
 @KONTROLSAHASIDEGERI  NVARCHAR(50),  
 @DBLOKUTULANMIKTAR DECIMAL(28,8),  
 @DBLOKUTULANBIRIM DECIMAL(28,8),
 @BYTARTANSIRALAMA TINYINT,  
 @TXTPALETNO NVARCHAR(20),
 @LNGBELGEKOD INT,
 @LNGESKILOKASYON INT=0
