AS

CREATE TABLE #LOKASYON (LNGKOD INT, TXTLOKASYONKOD NVARCHAR(50),TXTTANIMI NVARCHAR(100))
CREATE TABLE #USTLOKASYON (LNGUSTKOD INT)
CREATE TABLE #ONERILOKASYON (LNGKOD INT, LOKASYON NVARCHAR(50))
CREATE TABLE #ONERILOKASYONURUN (LNGKOD INT, LOKASYON NVARCHAR(50))
CREATE TABLE #STOKDURUM (LNGKOD INT, TXTTANIMI  NVARCHAR(50))
CREATE TABLE #BOSLOKASYONLAR (LNGKOD INT, TXTLOKASYONKOD NVARCHAR(50), DBLPALETMIKTAR INT, BOSMIK INT)
CREATE TABLE #KAPSAMKONTROL (LNGKOD INT, TXTTANIMI  NVARCHAR(50))


INSERT INTO #KAPSAMKONTROL
		SELECT  L.LNGKOD AS LNGKOD , L.TXTTANIMI AS LOKASYON FROM TBLSBBELGEKAPSAM BK
		INNER JOIN TBLSBBELGEDETAY BD ON BD.LNGKOD=BK.LNGDETAYKOD
		INNER JOIN TBLSBBELGEBASLIK BB ON BB.LNGKOD=BD.LNGBASLIKKOD
		INNER JOIN TBLSBLOKASYON L ON L.LNGKOD=BK.LNGHEDEFLOKASYONKOD
		WHERE BB.BYTBELGEDURUM =7 AND BB.LNGOPERASYONTIPKOD=1241 AND BD.LNGMALZEMEKOD=@LNGMALZEME AND BB.LNGDISTKOD=8

INSERT INTO #BOSLOKASYONLAR
	SELECT  *  FROM (
	SELECT L.LNGKOD, L.TXTLOKASYONKOD, LK.DBLPALETMIKTAR, (LK.DBLPALETMIKTAR-COUNT(SD.LNGLOKASYONKOD)-COUNT(KAPSAM.LNGKOD)) AS BOSMIK FROM TBLSBLOKASYON L WITH(NOLOCK)
	INNER JOIN TBLSBLOKASYONKAPASITE LK WITH(NOLOCK) ON LK.LNGLOKASYONBAGLANTIKODU=L.LNGKOD	
	LEFT JOIN TBLSBSTOKDURUM SD WITH(NOLOCK) ON SD.LNGLOKASYONKOD=L.LNGKOD
	LEFT JOIN #KAPSAMKONTROL KAPSAM WITH(NOLOCK) ON KAPSAM.LNGKOD=L.LNGKOD
	WHERE SUBSTRING(L.TXTLOKASYONKOD,6,2)<>'01'  AND L.LNGDISTKOD=8
	GROUP BY L.TXTLOKASYONKOD, LK.DBLPALETMIKTAR, L.LNGKOD) BOSRAF WHERE
	BOSMIK>0 ORDER BY TXTLOKASYONKOD


INSERT INTO #STOKDURUM
		SELECT DISTINCT L.LNGKOD AS LNGKOD , L.TXTTANIMI AS LOKASYON  FROM TBLSBLOKASYON L WITH(NOLOCK)
		INNER JOIN TBLSBSTOKDURUM S WITH(NOLOCK) ON S.LNGLOKASYONKOD=L.LNGKOD
		WHERE LEN(L.TXTLOKASYONKOD)=7 AND LNGMALZEMEKOD=@LNGMALZEME AND L.LNGDISTKOD=8

INSERT INTO #USTLOKASYON
SELECT DISTINCT * FROM (
				SELECT DISTINCT LNGUSTKOD FROM TBLSBLOKASYON L WITH(NOLOCK)
		INNER JOIN TBLSBSTOKDURUM S WITH(NOLOCK) ON S.LNGLOKASYONKOD=L.LNGKOD
		INNER JOIN TBLSBLOKASYONKAPASITE LK WITH(NOLOCK) ON LK.LNGLOKASYONBAGLANTIKODU=L.LNGKOD
		WHERE LEN(L.TXTLOKASYONKOD)=7 AND LNGMALZEMEKOD=@LNGMALZEME  AND L.LNGDISTKOD=8
		UNION ALL
				SELECT DISTINCT LNGUSTKOD FROM TBLSBLOKASYON L WITH(NOLOCK)
		INNER JOIN  #KAPSAMKONTROL S  ON S.LNGKOD=L.LNGKOD
		INNER JOIN TBLSBLOKASYONKAPASITE LK WITH(NOLOCK) ON LK.LNGLOKASYONBAGLANTIKODU=L.LNGKOD
		WHERE LEN(L.TXTLOKASYONKOD)=7 AND L.LNGDISTKOD=8 ) A

INSERT INTO #ONERILOKASYON
