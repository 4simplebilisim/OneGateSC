		SELECT L.LNGKOD,  L.TXTLOKASYONKOD, LK.DBLPALETMIKTAR, (LK.DBLPALETMIKTAR-COUNT(SD.LNGLOKASYONKOD)-COUNT(KAPSAM.LNGKOD)) AS BOSMIK FROM TBLSBLOKASYON L WITH(NOLOCK)
		INNER JOIN TBLSBLOKASYONKAPASITE LK WITH(NOLOCK) ON LK.LNGLOKASYONBAGLANTIKODU=L.LNGKOD
		INNER JOIN #USTLOKASYON UST WITH(NOLOCK) ON UST.LNGUSTKOD=L.LNGUSTKOD
		LEFT JOIN TBLSBSTOKDURUM SD WITH(NOLOCK) ON SD.LNGLOKASYONKOD=L.LNGKOD
		LEFT JOIN #KAPSAMKONTROL KAPSAM WITH(NOLOCK) ON KAPSAM.LNGKOD=L.LNGKOD
		WHERE SUBSTRING(L.TXTLOKASYONKOD,6,2)<>'01'  AND L.LNGDISTKOD=8
		GROUP BY L.LNGKOD, L.TXTLOKASYONKOD, LK.DBLPALETMIKTAR) BOSRAF
