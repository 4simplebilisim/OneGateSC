CREATE PROCEDURE [dbo].[SSP_SBSEPETDAGIT_ORJ] (@LNGDISTKOD INT, @LNGBELGEKODLIST NVARCHAR(MAX), @DEVMODE TINYINT = 0)
AS
BEGIN

CREATE TABLE #BELGELIST (LNGKOD INTEGER, LNGOPERASYONTIPKOD INTEGER, TXTPLAKA NVARCHAR(50), TXTDAGITIMYONU NVARCHAR(1), TXTDURUM NVARCHAR(50))
CREATE TABLE #BELGEDETAYLIST (LNGBASLIKKOD INTEGER, LNGDETAYKOD INTEGER, TXTURUNGRUP NVARCHAR(10), TXTURUNUSTGRUP NVARCHAR(10),DBLDETAYHACIM DECIMAL(28,8), LNGURUNKOD INT, 
 DBLMIKTAR DECIMAL(28,8), DBLISLEMBIRIMHACIM DECIMAL(28,8), LNGISLEMOLCUBIRIM INT, TXTDAGITIMYONU NVARCHAR(1), DBLKALANMIKTAR DECIMAL(28,8))
CREATE TABLE #SEPETLER (TXTPLAKA NVARCHAR(50), TXTANASEPET NVARCHAR(50), TXTALTSEPET NVARCHAR(50), DBLSEPETHACIM DECIMAL(28,8), DBLYUKLENENHACIM DECIMAL(28,8) DEFAULT 0, TXTSEPETDAGITIMYONU NVARCHAR(1) 
 , TXTSEPETURUNGRUBU NVARCHAR(50), TXTSEPETURUNUSTGRUBU NVARCHAR(50))
CREATE TABLE #SEPETBELGE (LNGBELGEKOD INT, LNGBELGEDETAYKOD INT, TXTGECICISEPET NVARCHAR(50), LNGURUNKOD INT, DBLMIKTAR DECIMAL(28,8), DBLOLCUBIRIMHACIM DECIMAL(28,8), LNGISLEMOLCUBIRIM INT
   , TXTURUNGRUP NVARCHAR(50), TXTURUNUSTGRUP NVARCHAR(50))


DECLARE @DONULECEKPLAKA AS NVARCHAR(20)
      DECLARE XPLAKA CURSOR FAST_FORWARD FOR SELECT DISTINCT TXTPLAKANO FROM VIEWSBSEPETDAGITIM WHERE LNGKOD IN (SELECT * FROM STRING_SPLIT(@LNGBELGEKODLIST, ',') )
      OPEN XPLAKA
      FETCH NEXT FROM XPLAKA INTO @DONULECEKPLAKA
      WHILE(@@FETCH_STATUS = 0)
      BEGIN
      
  /*** VERİHAZIRLANIYOR, KONTROLLER YAPILIYOR***/
  DELETE FROM #BELGELIST
  INSERT INTO #BELGELIST (LNGKOD, LNGOPERASYONTIPKOD, TXTPLAKA, TXTDAGITIMYONU, TXTDURUM)
  SELECT BELGE.LNGKOD, BB.LNGOPERASYONTIPKOD, BELGE.TXTPLAKANO, SUBSTRING(EKSAHA.TXTEKSAHAACIKLAMA,1,1), BELGE.TXTDURUM 
    FROM VIEWSBSEPETDAGITIM BELGE
	INNER JOIN TBLSBBELGEBASLIK BB (NOLOCK) ON BB.LNGKOD = BELGE.LNGKOD
	LEFT OUTER JOIN TBLSBBELGEBASLIKEKSAHA EKSAHA (NOLOCK) ON EKSAHA.LNGBAGLANTIKOD = BELGE.LNGKOD AND EKSAHA.LNGEKSAHAKODU IN (SELECT LNGTAKIPKOD FROM TBLEKSAHATANIMLAMA WHERE TXTACIKLAMA = 'DagitimYonu')
   WHERE BELGE.LNGKOD IN (SELECT * FROM STRING_SPLIT(@LNGBELGEKODLIST, ','))
   AND BELGE.TXTPLAKANO = @DONULECEKPLAKA

   IF (SELECT COUNT(1) FROM #BELGELIST WHERE TXTDURUM = 'ATANMIŞ') > 0 AND @DEVMODE = 0 
   BEGIN
     RAISERROR('Atanmış kayıtlar için dağıtım yapılamaz',16,1)
	 RETURN
   END

  DECLARE @HEPSIYONDEGERI NVARCHAR(1) = 'H',@Mesaj NVARCHAR(MAX)
   
  DECLARE @DAGITIMYONUZORUNLU TINYINT
  SELECT @DAGITIMYONUZORUNLU = CASE WHEN ISNULL(TXTDEGER,'') = 'X' THEN 1 ELSE 0 END FROM TBLSBBELGEPARAMETRE WHERE BYTPARAMETRE = 43 AND LNGBELGETIPKOD IN (SELECT LNGOPERASYONTIPKOD FROM #BELGELIST)
  IF (@DAGITIMYONUZORUNLU = 1)
  BEGIN
   IF (SELECT COUNT(1) FROM #BELGELIST WHERE ISNULL(TXTDAGITIMYONU,'') = '') > 0
   BEGIN
    RAISERROR('Belgelerde dağıtım yönü bulunamadığı için işlem yapılamadı!',16,1)
    RETURN 
   END
  END

  /* GEÇİCİ OLARAK KAPATILDI AÇILACAK !!!!!!!!!!*/
  IF (
  SELECT COUNT(1) FROM VIEWSBSEPETDAGITIM V 
   WHERE V.LNGKOD NOT IN (SELECT B.LNGKOD FROM #BELGELIST B)
     AND V.TXTPLAKANO IN (SELECT B.TXTPLAKA FROM #BELGELIST B) ) > 0  AND @DEVMODE = 0 
	 BEGIN
	  RAISERROR('Plakaya ait tüm belgeler seçilmediğinden dağıtım yapılmayacak!',16,1)
      RETURN 
	 END
/**/
   IF (@DAGITIMYONUZORUNLU = 1)
   BEGIN
    UPDATE #BELGELIST
     SET TXTDAGITIMYONU = @HEPSIYONDEGERI
   WHERE ISNULL(TXTDAGITIMYONU,'') = ''
    END
   ELSE
   BEGIN
    SET @HEPSIYONDEGERI = 'X'
   UPDATE #BELGELIST
      SET TXTDAGITIMYONU = @HEPSIYONDEGERI
   END 

  DELETE FROM #BELGEDETAYLIST
  INSERT INTO #BELGEDETAYLIST (LNGBASLIKKOD, LNGDETAYKOD, TXTURUNGRUP, TXTURUNUSTGRUP, DBLDETAYHACIM, LNGURUNKOD, DBLMIKTAR, DBLISLEMBIRIMHACIM, LNGISLEMOLCUBIRIM, TXTDAGITIMYONU, DBLKALANMIKTAR)
  SELECT BD.LNGBASLIKKOD, BD.LNGKOD, UG.TXTKOD, UG2.TXTKOD, BD.DBLISLEMMIKTARI*ISNULL(OB.DBLHACIM,0) , BD.LNGMALZEMEKOD, BD.DBLISLEMMIKTARI, 
  ISNULL(OB.DBLHACIM,0), BD.LNGISLEMOLCUBIRIMKOD, 
   B.TXTDAGITIMYONU ,BD.DBLISLEMMIKTARI
    FROM TBLSBBELGEDETAY BD (NOLOCK)
 INNER JOIN TBLSBURUNOLCUBIRIM OB (NOLOCK) ON BD.LNGMALZEMEKOD = OB.LNGURUNKOD AND OB.LNGBIRIMKOD = BD.LNGISLEMOLCUBIRIMKOD 
 LEFT OUTER JOIN TBLSBURUNEKGRUPBAGLANTI UGB (NOLOCK) ON UGB.LNGSIRANO = 2 AND UGB.LNGURUNKOD = BD.LNGMALZEMEKOD
 LEFT OUTER JOIN TBLSBGRUP UG (NOLOCK) ON UG.LNGKOD = UGB.LNGGRUPKOD
 LEFT OUTER JOIN TBLSBURUNEKGRUPBAGLANTI UGB2 (NOLOCK) ON UGB2.LNGSIRANO = 1 AND UGB2.LNGURUNKOD = BD.LNGMALZEMEKOD
 LEFT OUTER JOIN TBLSBGRUP UG2 (NOLOCK) ON UG2.LNGKOD = UGB2.LNGGRUPKOD
 INNER JOIN #BELGELIST B ON B.LNGKOD = BD.LNGBASLIKKOD  

 --IF (SELECT COUNT(1) FROM #BELGEDETAYLIST WHERE ISNULL(DBLDETAYHACIM,0) = 0) > 0
 --BEGIN
 -- RAISERROR('Seçilen belge detaylarında hacim hesaplanmadığı için dağıtım yapılamamıştır. Ürün ölçü birim hacim değerlerini kontrol ediniz!',16,1)
 -- RETURN
 --END
  DECLARE @URUNKOD NVARCHAR(50) = ''
  IF (SELECT COUNT(1) FROM #BELGEDETAYLIST WHERE ISNULL(DBLDETAYHACIM,0) = 0) > 0
 BEGIN
 SELECT @URUNKOD=U.TXTKOD FROM #BELGEDETAYLIST D 
 INNER JOIN TBLURUN U ON U.LNGKOD=D.LNGURUNKOD
 WHERE ISNULL(DBLDETAYHACIM,0) = 0
 SET @Mesaj='Seçilen belge detaylarında hacim hesaplanmadığı için dağıtım yapılamamıştır. ' + @URUNKOD +' kodlu ürüne ait ölçü birim hacim değerlerini kontrol ediniz!'
  RAISERROR(@Mesaj,16,1)
  RETURN
 END
 
 IF (SELECT COUNT(1) FROM #BELGEDETAYLIST WHERE ISNULL(TXTURUNGRUP,'') = '') > 0
 BEGIN
  RAISERROR('Seçilen belge detaylarında ürün grup bağlantısı yapılmadığı için dağıtım yapılamamıştır!',16,1)
  RETURN
 END

  DELETE FROM #SEPETLER
  DECLARE @PLAKA NVARCHAR(50)
  DECLARE XCURSOR_ARAC CURSOR FAST_FORWARD FOR SELECT DISTINCT TXTPLAKA FROM #BELGELIST
  OPEN XCURSOR_ARAC
  FETCH NEXT FROM XCURSOR_ARAC INTO @PLAKA
  WHILE(@@FETCH_STATUS = 0)
  BEGIN     
         DECLARE @SEPET_ADI NVARCHAR(50), @SEPET_HACIM DECIMAL(28,8), @SEPET_SAYISI INT
		 DECLARE @i INT = 1
		 SELECT @SEPET_ADI = ST.TXTKOD, 
		        @SEPET_HACIM = ST.DBLHACIM + ISNULL(ST.DBLHACIMTOLERANS,0), 
				@SEPET_SAYISI = STB.LNGSEPETSAYISI
		   FROM TBLSBSEPETTIPI ST (NOLOCK)
	 INNER JOIN TBLSBARACTIPISEPETTIPIBAGLANTI STB (NOLOCK) ON STB.LNGSEPETTIPKOD = ST.LNGKOD
	 INNER JOIN TBLSBARAC ARAC (NOLOCK) ON ARAC.LNGARACTIPKOD = STB.LNGARACTIPKOD
		  WHERE ARAC.TXTPLAKA = @PLAKA

		  WHILE @i <= @SEPET_SAYISI
		  BEGIN
		    INSERT INTO #SEPETLER (TXTPLAKA, TXTANASEPET, TXTALTSEPET, DBLSEPETHACIM)
			SELECT @PLAKA, @SEPET_ADI, @SEPET_ADI+'_'+CONVERT(NVARCHAR,@i), @SEPET_HACIM
			SET @i = @i+1
		  END
        FETCH NEXT FROM XCURSOR_ARAC INTO @PLAKA
  END
  CLOSE XCURSOR_ARAC
  DEALLOCATE XCURSOR_ARAC
  
  DECLARE @SORUNLUARAC NVARCHAR(50), @SORUNLUARACHACIM  NVARCHAR(50), @SORUNLUARACBELGETOPLAMHACIM  NVARCHAR(50)
  SELECT TOP 1 @SORUNLUARAC = AA.TXTPLAKA, @SORUNLUARACHACIM = AA.ARACHACIM, @SORUNLUARACBELGETOPLAMHACIM = AA.BELGEHACIM  FROM (
  SELECT S.TXTPLAKA, SUM(DBLSEPETHACIM) ARACHACIM ,  (SELECT SUM(DBLDETAYHACIM)      
	FROM #BELGELIST B INNER JOIN #BELGEDETAYLIST BD ON BD.LNGBASLIKKOD = B.LNGKOD WHERE  B.TXTPLAKA = S.TXTPLAKA) BELGEHACIM
    FROM #SEPETLER S	
	GROUP BY S.TXTPLAKA ) AA
	WHERE AA.ARACHACIM - AA.BELGEHACIM < 0
	 
	IF (ISNULL(@SORUNLUARAC,'') <> '')
	BEGIN
	  DECLARE @MSJ NVARCHAR(250) = @SORUNLUARAC + ' plakalı araç hacmi=' + @SORUNLUARACHACIM  +' m3 ,seçilen siparişlerin hacmi='+@SORUNLUARACBELGETOPLAMHACIM+' m3 olduğundan işlem yapılamaz'
	  RAISERROR(@MSJ,16,1)
	  RETURN
	END

IF (SELECT COUNT(1) FROM #SEPETLER ) = 0 
 BEGIN
  RAISERROR('Sepet olmadığı için dağıtım yapılamamıştır. Sepet tanımlarını kontrol ediniz!',16,1)
  RETURN
 END

	DECLARE @SORUNLUPLAKA NVARCHAR(50) = NULL, @SORUNLUYON NVARCHAR(1)
	 SELECT DISTINCT  @SORUNLUPLAKA = TXTPLAKA, @SORUNLUYON = TXTDAGITIMYONU  FROM (
	 SELECT #BELGELIST.TXTPLAKA, SUM(#BELGEDETAYLIST.DBLDETAYHACIM) BELGEDETAYTOPLAMHACIM ,(SELECT SUM(#SEPETLER.DBLSEPETHACIM) 
	                                                        FROM #SEPETLER 
														WHERE #SEPETLER.TXTPLAKA = #BELGELIST.TXTPLAKA ) ARACHACIM 
	 , #BELGEDETAYLIST.TXTDAGITIMYONU  FROM #BELGEDETAYLIST 
	 INNER JOIN #BELGELIST ON #BELGELIST.LNGKOD =#BELGEDETAYLIST.LNGBASLIKKOD 
	 WHERE #BELGEDETAYLIST.TXTDAGITIMYONU <> @HEPSIYONDEGERI
	 GROUP BY #BELGEDETAYLIST.TXTDAGITIMYONU ,#BELGEDETAYLIST.LNGBASLIKKOD,#BELGELIST.TXTPLAKA )AA
	 GROUP BY TXTPLAKA, ARACHACIM,TXTDAGITIMYONU
	  HAVING  SUM (BELGEDETAYTOPLAMHACIM)  > ARACHACIM /2

 IF (@SORUNLUPLAKA IS NOT NULL) AND (@DAGITIMYONUZORUNLU = 1)
	  BEGIN
	  DECLARE @MSJ2 NVARCHAR(500) = @SORUNLUPLAKA + ' plakalı araçta '+@SORUNLUYON+' yönü araç hacmini aşıyor.Dağıtım yapılamaz! '
	   RAISERROR(@MSJ2,16,1)
       RETURN
	  END

    DELETE FROM #SEPETBELGE

	/*** DAĞITIM BAŞLIYOR ***/
	BEGIN
	  DECLARE @BELGEKOD INT, @BELGEDETAYKOD INT, @URUNGRUP NVARCHAR(50), @HACIM DECIMAL(28,8), @YON NVARCHAR, @URUNUSTGRUP NVARCHAR(50)
      DECLARE XBELGEDAGITIM CURSOR FAST_FORWARD FOR SELECT DISTINCT B.LNGKOD, BD.LNGDETAYKOD, BD.TXTURUNGRUP, BD.TXTURUNUSTGRUP, SUM(BD.DBLDETAYHACIM) , B.TXTDAGITIMYONU
	  FROM #BELGELIST B INNER JOIN #BELGEDETAYLIST BD ON BD.LNGBASLIKKOD = B.LNGKOD
	  GROUP BY B.LNGKOD, BD.LNGDETAYKOD, BD.TXTURUNGRUP, B.TXTDAGITIMYONU, BD.TXTURUNUSTGRUP 
	  ORDER BY 5 DESC
      OPEN XBELGEDAGITIM
      FETCH NEXT FROM XBELGEDAGITIM INTO @BELGEKOD, @BELGEDETAYKOD, @URUNGRUP, @URUNUSTGRUP, @HACIM, @YON
      WHILE(@@FETCH_STATUS = 0)
      BEGIN
            DECLARE @GECICISEPET NVARCHAR(50)=  NULL
            SELECT TOP 1 @GECICISEPET = S.TXTALTSEPET FROM #SEPETLER S
			WHERE (S.TXTSEPETURUNGRUBU IS NULL OR S.TXTSEPETURUNGRUBU  = @URUNGRUP)
			  AND ( @YON = @HEPSIYONDEGERI OR S.TXTSEPETDAGITIMYONU IS NULL OR S.TXTSEPETDAGITIMYONU = @YON)
			  AND S.DBLSEPETHACIM - S.DBLYUKLENENHACIM >= @HACIM
			  ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM ASC, TXTALTSEPET			
			  --ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM DESC, TXTALTSEPET		' HOMOJEN DAĞITILACAKSA AÇILACAK	
			
			IF (@GECICISEPET IS NULL)
			BEGIN
			   SELECT TOP 1 @GECICISEPET = S.TXTALTSEPET FROM #SEPETLER S
			WHERE (S.TXTSEPETURUNUSTGRUBU IS NULL OR S.TXTSEPETURUNUSTGRUBU  = @URUNUSTGRUP)
			  AND ( @YON = @HEPSIYONDEGERI OR S.TXTSEPETDAGITIMYONU IS NULL OR S.TXTSEPETDAGITIMYONU = @YON)
			  AND S.DBLSEPETHACIM - S.DBLYUKLENENHACIM >= @HACIM
			  ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM ASC, TXTALTSEPET			
			  --ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM DESC, TXTALTSEPET		' HOMOJEN DAĞITILACAKSA AÇILACAK	
			END	

			IF (@GECICISEPET IS NULL)
			BEGIN
			  SELECT TOP 1 @GECICISEPET = S.TXTALTSEPET FROM #SEPETLER S
			   WHERE S.DBLSEPETHACIM - S.DBLYUKLENENHACIM >= @HACIM
			    AND (@YON = @HEPSIYONDEGERI OR S.TXTSEPETDAGITIMYONU IS NULL OR S.TXTSEPETDAGITIMYONU = @YON)
			  ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM ASC, TXTALTSEPET			
			  --ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM DESC, TXTALTSEPET		' HOMOJEN DAĞITILACAKSA AÇILACAK	
			END			
			
			IF (@GECICISEPET IS NOT NULL)			
			BEGIN
			  INSERT INTO #SEPETBELGE (LNGBELGEKOD, LNGBELGEDETAYKOD, TXTGECICISEPET, LNGURUNKOD, DBLMIKTAR, DBLOLCUBIRIMHACIM, LNGISLEMOLCUBIRIM, TXTURUNGRUP )
			  SELECT @BELGEKOD, @BELGEDETAYKOD, @GECICISEPET, BD.LNGURUNKOD, BD.DBLMIKTAR, BD.DBLISLEMBIRIMHACIM, BD.LNGISLEMOLCUBIRIM, @URUNGRUP
			    FROM #BELGEDETAYLIST BD
		       WHERE BD.LNGBASLIKKOD = @BELGEKOD AND BD.LNGDETAYKOD = @BELGEDETAYKOD

			  UPDATE #SEPETLER
			     SET DBLYUKLENENHACIM = DBLYUKLENENHACIM + @HACIM,
				     TXTSEPETDAGITIMYONU = CASE WHEN TXTSEPETDAGITIMYONU IS NULL THEN @YON ELSE TXTSEPETDAGITIMYONU END,
					 TXTSEPETURUNGRUBU = CASE WHEN TXTSEPETURUNGRUBU IS NULL THEN @URUNGRUP ELSE TXTSEPETURUNGRUBU END,
					 TXTSEPETURUNUSTGRUBU = CASE WHEN TXTSEPETURUNUSTGRUBU IS NULL THEN @URUNUSTGRUP ELSE TXTSEPETURUNUSTGRUBU END
			   WHERE TXTALTSEPET = @GECICISEPET

			   UPDATE #BELGEDETAYLIST
				    SET #BELGEDETAYLIST.DBLKALANMIKTAR = 0
					WHERE #BELGEDETAYLIST.LNGDETAYKOD =@BELGEDETAYKOD AND #BELGEDETAYLIST.LNGBASLIKKOD = @BELGEKOD 
			END
			
            FETCH NEXT FROM XBELGEDAGITIM INTO @BELGEKOD, @BELGEDETAYKOD, @URUNGRUP, @URUNUSTGRUP, @HACIM, @YON
      END
      CLOSE XBELGEDAGITIM
      DEALLOCATE XBELGEDAGITIM	
	END
	
/***R siparişi boşta kaldı ve H de sepet varsa***/
IF (SELECT COUNT(1)
  FROM #BELGEDETAYLIST BD 
 WHERE (BD.LNGDETAYKOD) NOT IN (SELECT S.LNGBELGEDETAYKOD FROM #SEPETBELGE S) AND BD.TXTDAGITIMYONU = 'R') > 0 
  AND (SELECT COUNT(1) FROM #SEPETLER WHERE TXTSEPETDAGITIMYONU = @HEPSIYONDEGERI AND DBLSEPETHACIM - DBLYUKLENENHACIM > 0) > 0
	BEGIN  
   DECLARE @RBELGEKOD INT, @RBELGEDETAYKOD INT, @RURUNGRUP NVARCHAR(50), @RURUNUSTGRUP NVARCHAR(50), @RHACIM DECIMAL(28,8)  
      DECLARE XRIGHT CURSOR FAST_FORWARD FOR SELECT DISTINCT B.LNGKOD, BD.LNGDETAYKOD, BD.TXTURUNGRUP, BD.TXTURUNUSTGRUP, SUM(BD.DBLDETAYHACIM)   
   FROM #BELGELIST B INNER JOIN #BELGEDETAYLIST BD ON BD.LNGBASLIKKOD = B.LNGKOD 
   WHERE (BD.LNGDETAYKOD) NOT IN (SELECT S.LNGBELGEDETAYKOD FROM #SEPETBELGE S) AND BD.TXTDAGITIMYONU = 'R'  
   GROUP BY B.LNGKOD, BD.LNGDETAYKOD, BD.TXTURUNGRUP, BD.TXTURUNUSTGRUP
   ORDER BY 5 DESC  
      OPEN XRIGHT  
      FETCH NEXT FROM XRIGHT INTO @RBELGEKOD, @RBELGEDETAYKOD, @RURUNGRUP, @RURUNUSTGRUP, @RHACIM  
      WHILE(@@FETCH_STATUS = 0)  
      BEGIN  
            DECLARE @RGECICISEPET NVARCHAR(50) =  NULL  
            SELECT TOP 1 @RGECICISEPET = S.TXTALTSEPET FROM #SEPETLER S  
   WHERE S.TXTSEPETURUNGRUBU = @RURUNGRUP
     AND S.TXTSEPETDAGITIMYONU  IN ('R', @HEPSIYONDEGERI)
     AND S.DBLSEPETHACIM - S.DBLYUKLENENHACIM >= @RHACIM  
     ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM ASC, TXTALTSEPET     
     --ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM DESC, TXTALTSEPET  ' HOMOJEN DAĞITILACAKSA AÇILACAK   

   IF (@RGECICISEPET IS NULL)  
   BEGIN  
      SELECT TOP 1 @RGECICISEPET = S.TXTALTSEPET FROM #SEPETLER S  
   WHERE S.TXTSEPETURUNUSTGRUBU = @RURUNUSTGRUP
     AND S.TXTSEPETDAGITIMYONU  IN ('R', @HEPSIYONDEGERI)
     AND S.DBLSEPETHACIM - S.DBLYUKLENENHACIM >= @RHACIM  
     ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM ASC, TXTALTSEPET     
     --ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM DESC, TXTALTSEPET  ' HOMOJEN DAĞITILACAKSA AÇILACAK   
   END     
          

   IF (@RGECICISEPET IS NULL)  
   BEGIN  
     SELECT TOP 1 @RGECICISEPET = S.TXTALTSEPET FROM #SEPETLER S  
      WHERE S.DBLSEPETHACIM - S.DBLYUKLENENHACIM >= @RHACIM  
        AND S.TXTSEPETDAGITIMYONU  IN ('R', @HEPSIYONDEGERI)
     ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM ASC, TXTALTSEPET     
     --ORDER BY S.DBLSEPETHACIM - S.DBLYUKLENENHACIM DESC, TXTALTSEPET  ' HOMOJEN DAĞITILACAKSA AÇILACAK   
   END     
     
   IF (@RGECICISEPET IS NOT NULL)     
   BEGIN  
    INSERT INTO #SEPETBELGE (LNGBELGEKOD, LNGBELGEDETAYKOD, TXTGECICISEPET, LNGURUNKOD, DBLMIKTAR, DBLOLCUBIRIMHACIM, LNGISLEMOLCUBIRIM, TXTURUNGRUP )  
     SELECT @RBELGEKOD, @RBELGEDETAYKOD, @RGECICISEPET, BD.LNGURUNKOD, BD.DBLMIKTAR, BD.DBLISLEMBIRIMHACIM, BD.LNGISLEMOLCUBIRIM  , @RURUNGRUP
       FROM #BELGEDETAYLIST BD  
         WHERE BD.LNGBASLIKKOD = @RBELGEKOD AND BD.LNGDETAYKOD = @RBELGEDETAYKOD  
  
     UPDATE #SEPETLER  
        SET DBLYUKLENENHACIM = DBLYUKLENENHACIM + @RHACIM,  
         TXTSEPETDAGITIMYONU = 'R',  
      TXTSEPETURUNGRUBU = CASE WHEN TXTSEPETURUNGRUBU IS NULL THEN @RURUNGRUP ELSE TXTSEPETURUNGRUBU END  ,
	  TXTSEPETURUNUSTGRUBU = CASE WHEN TXTSEPETURUNUSTGRUBU IS NULL THEN @RURUNUSTGRUP ELSE TXTSEPETURUNUSTGRUBU END  
      WHERE TXTALTSEPET = @RGECICISEPET  

	  UPDATE #BELGEDETAYLIST
         SET DBLKALANMIKTAR = 0
         WHERE LNGDETAYKOD =@RBELGEDETAYKOD AND LNGBASLIKKOD =  @RBELGEKOD
   END    
     
            FETCH NEXT FROM XRIGHT INTO @RBELGEKOD, @RBELGEDETAYKOD, @RURUNGRUP, @RURUNUSTGRUP, @RHACIM  
      END  
      CLOSE XRIGHT  
      DEALLOCATE XRIGHT   
 END  

/***L siparişi boşta kaldı ve H de sepet varsa***/
IF (SELECT COUNT(1)
  FROM #BELGEDETAYLIST BD 
 WHERE (BD.LNGDETAYKOD) NOT IN (SELECT S.LNGBELGEDETAYKOD FROM #SEPETBELGE S) AND BD.TXTDAGITIMYONU = 'L') > 0 
  AND (SELECT COUNT(1) FROM #SEPETLER WHERE TXTSEPETDAGITIMYONU = @HEPSIYONDEGERI AND DBLSEPETHACIM - DBLYUKLENENHACIM > 0) > 0
	BEGIN  
   DECLARE @LBELGEKOD INT, @LBELGEDETAYKOD INT, @LURUNGRUP NVARCHAR(50), @LURUNUSTGRUP NVARCHAR(50), @LHACIM DECIMAL(28,8)  
      DECLARE XLEFT CURSOR FAST_FORWARD FOR SELECT DISTINCT B.LNGKOD, BD.LNGDETAYKOD, BD.TXTURUNGRUP, BD.TXTURUNUSTGRUP, SUM(BD.DBLDETAYHACIM)   
   FROM #BELGELIST B INNER JOIN #BELGEDETAYLIST BD ON BD.LNGBASLIKKOD = B.LNGKOD 
   WHERE (BD.LNGDETAYKOD) NOT IN (SELECT S.LNGBELGEDETAYKOD FROM #SEPETBELGE S) AND BD.TXTDAGITIMYONU = 'R'  
   GROUP BY B.LNGKOD, BD.LNGDETAYKOD, BD.TXTURUNGRUP, BD.TXTURUNUSTGRUP  
