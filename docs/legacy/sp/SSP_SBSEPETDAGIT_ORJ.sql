			       SB.LNGURUNKOD LNGMALZEMEKOD, ((SB.DBLMIKTAR*UOB.DBLCARPAN)/UOB.DBLBOLEN) DBLMIKTAR, (SELECT UOB2.LNGBIRIMKOD 
				   FROM TBLSBURUNOLCUBIRIM UOB2 (NOLOCK) WHERE UOB2.LNGURUNKOD =SB.LNGURUNKOD AND UOB2.BYTANAOLCUBIRIMI = 1 ) LNGBIRIMKOD, 0 DBLTOPLANANMIKTAR , 
				   GETDATE() TRHILKISLEMTARIHI, 1 LNGILKKULLANICIKOD, SB.TXTGECICISEPET
			  FROM #SEPETLER S
		INNER JOIN #SEPETBELGE SB ON SB.TXTGECICISEPET = S.TXTALTSEPET
		LEFT OUTER JOIN TBLSBSEPETDAGITIMBASLIK DB (NOLOCK) ON DB.LNGDAGITIMNO = @DSIRA AND DB.TXTGECICISEPETKAPAK = SB.TXTGECICISEPET
		INNER JOIN TBLSBURUNOLCUBIRIM UOB(NOLOCK) ON UOB.LNGBIRIMKOD = SB.LNGISLEMOLCUBIRIM AND UOB.LNGURUNKOD = SB.LNGURUNKOD 
			 WHERE S.TXTPLAKA = @DPLAKA ) AA
			 GROUP BY LNGSEPETBASLIKKOD,  LNGBELGEBASLIKKOD,  LNGBELGEDETAYKOD, 
			        LNGMALZEMEKOD, LNGBIRIMKOD, DBLTOPLANANMIKTAR , 
				    TRHILKISLEMTARIHI, LNGILKKULLANICIKOD, TXTGECICISEPET
END
