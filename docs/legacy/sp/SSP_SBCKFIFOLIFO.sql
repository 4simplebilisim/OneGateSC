CREATE TABLE #TBL (LOKASYON INT PRIMARY KEY)     

CREATE TABLE #STOKLAR(LNGLOKASYONKOD INT,LNGPALETID INT, TXTBATCHNO NVARCHAR(50),TXTSERINO NVARCHAR(50),TXTPO NVARCHAR(50),TXTPOLINE NVARCHAR(50),LNGKOD INT,LNGMALZEMEKOD INT,LNGSTATUKOD INT,LNGMUSTERIKOD INT,DBLANAMIKTAR DECIMAL(28,8),DBLREZERVEMIKTAR DECIMAL(28,8),          
 LNGANAOLCUBIRIMI INT,DBLNETAGIRLIK DECIMAL(28,8),DBLBRUTAGIRLIK DECIMAL(28,8),LNGAGIRLIKOLCUBIRIMI INT,TRHSONKULLANMATARIHI DATETIME,TRHURETIMTARIHI DATETIME,LNGREZERVEBELGEKOD INT,LNGREZERVEBELGETIPKOD INT,TRHILKISLEMTARIHI DATETIME,TRHSONISLEMTARIHI DATETIME)

 IF @LNGTOLERANS <24
 BEGIN
 SET @GUN=0
 END
 ELSE IF @LNGTOLERANS >=24 AND @LNGTOLERANS <48
 BEGIN
 SET @GUN=1
 END
 ELSE IF @LNGTOLERANS>=48 AND @LNGTOLERANS <72
 BEGIN
 SET @GUN=2
 END
 ELSE IF @LNGTOLERANS>=72 AND @LNGTOLERANS <96
 BEGIN
 SET @GUN=3
 END
 ELSE
 BEGIN
 SET @GUN=0
 END

  IF @TXTKONTROLSAHASI='TRHSONKULLANMATARIHI' AND CONVERT(DATE,@DTKONTROLSAHASIDEGERI) < GETDATE()
  SET @DTKONTROLSAHASIDEGERI =CONVERT(DATETIME, CONVERT(NVARCHAR(10), CONVERT(DATE,GETDATE())) + ' 00:00:00')

  PRINT(@DTKONTROLSAHASIDEGERI)

