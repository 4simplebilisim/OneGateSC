		   SET @TXTBATCHNO = @TXTBELGEHEDEFBATCH
		   SET @SQL+= ' AND TXTBATCHNO=''' + @TXTBELGEHEDEFBATCH + ''''   
		   END
	   IF ISNULL(@TXTBELGEKAYNAKBATCH,'') <> '' 
		   BEGIN
		   SET @TXTBATCHNO = @TXTBELGEKAYNAKBATCH
		   SET @SQL+= ' AND TXTBATCHNO=''' + @TXTBELGEKAYNAKBATCH + ''''  
		   END
	   IF ISNULL(@LNGBELGEPALETID,0) > 0 
		   BEGIN
		   SET @LNGPALETID = @LNGBELGEPALETID
		   SET @SQL+=  ' AND LNGPALETID=' + CONVERT(NVARCHAR,@LNGBELGEPALETID)    
		   END
	   IF ISNULL(@TXTBELGESERINO,'') <> '' 
		   BEGIN
		   SET @TXTSERINO = @TXTBELGESERINO
		   SET @SQL+=' AND TXTSERINO=''' + @TXTBELGESERINO + '''' 
		   END
	   IF ISNULL(@TXTBELGEPO,'') <> '' 
		   BEGIN
		   SET @TXTPO = @TXTBELGEPO
		   SET @SQL+=  ' AND TXTPO=''' + @TXTBELGEPO + ''''   
		   END
	   IF ISNULL(@TXTBELGEPOLINE,'') <> '' 
