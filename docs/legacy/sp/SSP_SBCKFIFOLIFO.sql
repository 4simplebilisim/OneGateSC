IF ISNULL(@LNGBELGEBASLIKKOD,0) > 0 
  
  
  BEGIN
	   DECLARE @TXTBELGEKAYNAKBATCH NVARCHAR(50)           
	   DECLARE @TXTBELGEHEDEFBATCH NVARCHAR(50)           
	   DECLARE @LNGBELGEPALETID INT
	   DECLARE @TXTBELGESERINO NVARCHAR(50)
	   DECLARE @TXTBELGEPO NVARCHAR(50)             
	   DECLARE @TXTBELGEPOLINE NVARCHAR(50)

	   SELECT top 1 @TXTBELGEKAYNAKBATCH = D.TXTKAYNAKBATCHNO, @TXTBELGEHEDEFBATCH = D.TXTHEDEFBATCHNO, @LNGBELGEPALETID = P.LNGKOD, @TXTBELGESERINO = D.TXTSERINO, 
	          @TXTBELGEPO = D.TXTPO, @TXTBELGEPOLINE = D.TXTPOLINE
	   FROM TBLSBBELGEDETAY D (NOLOCK)
	   LEFT JOIN TBLSBPALET P (NOLOCK) ON P.TXTPALETNO = D.TXTPALETNO
	   INNER JOIN TBLSBSTOKDURUM S (NOLOCK) ON S.LNGMALZEMEKOD=D.LNGMALZEMEKOD 
	   AND CASE WHEN D.TXTHEDEFBATCHNO <>'' AND S.TXTBATCHNO=D.TXTHEDEFBATCHNO THEN 1 WHEN D.TXTHEDEFBATCHNO ='' THEN 1 ELSE 0 END = 1
	   AND CASE WHEN D.TXTSERINO <>'' AND S.TXTSERINO=D.TXTSERINO THEN 1 WHEN D.TXTSERINO ='' THEN 1 ELSE 0 END = 1
	   AND CASE WHEN D.TXTPO <>'' AND S.TXTPO=D.TXTPO THEN 1 WHEN D.TXTPO ='' THEN 1 ELSE 0 END = 1
	   AND CASE WHEN D.TXTPOLINE <>'' AND S.TXTPOLINE=D.TXTPO THEN 1 WHEN D.TXTPOLINE ='' THEN 1 ELSE 0 END = 1
	   AND CASE WHEN D.TXTPALETNO <>'' AND P.TXTPALETNO=D.TXTPALETNO THEN 1 WHEN D.TXTPALETNO ='' THEN 1 ELSE 0 END = 1
	   WHERE LNGBASLIKKOD = @LNGBELGEBASLIKKOD AND D.LNGMALZEMEKOD = @LNGMALZEME	  
	   	   
	   IF ISNULL(@TXTBELGEHEDEFBATCH,'') <> '' 
