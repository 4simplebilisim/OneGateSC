  WITH LOC(LNGKOD,LNGUSTKOD) AS (              
   SELECT LNGKOD,LNGUSTKOD FROM TBLSBLOKASYON WHERE EXISTS(SELECT LB.LNGLOKASYONKOD FROM TBLSBLOKASYONGRUPBAGLANTI LB WHERE TBLSBLOKASYON.LNGKOD=LB.LNGLOKASYONKOD AND LNGGRUPKOD=' + CONVERT(NVARCHAR(50),@LNGLOKASYON) + ' )   UNION ALL              
   SELECT E.LNGKOD,E.LNGUSTKOD             
   FROM TBLSBLOKASYON AS e              
   INNER JOIN LOC AS d ON e.LNGUSTKOD = D.LNGKOD )              
     INSERT INTO #TBL SELECT DISTINCT LNGKOD AS LOKASYON FROM LOC   
    SELECT SD.LNGLOKASYONKOD ,SD.LNGPALETID, SD.TXTBATCHNO,SD.TXTSERINO,SD.TXTPO,SD.TXTPOLINE,SD.LNGKOD,SD.LNGMALZEMEKOD,SD.LNGSTATUKOD,SD.LNGMUSTERIKOD,SD.DBLANAMIKTAR,SD.DBLREZERVEMIKTAR,          
SD.LNGANAOLCUBIRIMI,SD.DBLNETAGIRLIK,SD.DBLBRUTAGIRLIK,SD.LNGAGIRLIKOLCUBIRIMI,SD.TRHSONKULLANMATARIHI,SD.TRHURETIMTARIHI,
SD.LNGREZERVEBELGEKOD,SD.LNGREZERVEBELGETIPKOD,SD.TRHILKISLEMTARIHI,SD.TRHSONISLEMTARIHI 
 FROM TBLSBSTOKDURUM SD WITH(NOLOCK) 
 LEFT JOIN TBLSBPALET PAL ON PAL.LNGKOD=SD.LNGPALETID
 '
 
 SET @WHERE='            WHERE EXISTS(SELECT T.LOKASYON FROM #TBL T WHERE SD.LNGLOKASYONKOD=T.LOKASYON             
     AND LNGMALZEMEKOD=' + CONVERT(NVARCHAR(50),@LNGMALZEME) + ' AND LNGSTATUKOD=' + CONVERT(NVARCHAR(50),@LNGSTATU) + ')            
     AND DBLANAMIKTAR-DBLREZERVEMIKTAR>0  '                   

	SET @SQL2 ='            
 INSERT INTO #STOKLAR
    SELECT LNGLOKASYONKOD ,LNGPALETID, TXTBATCHNO,TXTSERINO,TXTPO,TXTPOLINE,LNGKOD,LNGMALZEMEKOD,LNGSTATUKOD,LNGMUSTERIKOD,DBLANAMIKTAR,DBLREZERVEMIKTAR,          
 LNGANAOLCUBIRIMI,DBLNETAGIRLIK,DBLBRUTAGIRLIK,LNGAGIRLIKOLCUBIRIMI,TRHSONKULLANMATARIHI,TRHURETIMTARIHI,LNGREZERVEBELGEKOD,LNGREZERVEBELGETIPKOD,TRHILKISLEMTARIHI,TRHSONISLEMTARIHI 
 FROM TBLSBSTOKDURUM SD WITH(NOLOCK)            
  WHERE DBLANAMIKTAR-DBLREZERVEMIKTAR>0  '   
END


IF @BYTONAYLISAYIMKONTROLUYAPILSIN=1
 BEGIN
 SET @SQLSAYIMFARK=' LEFT JOIN (SELECT FARK.DBLSAYILANMIKTAR,FARK.TXTPALETNO,FARK.TXTBATCHNO,FARK.TXTSERINO,FARK.TXTPO,FARK.TXTPOLINE,FARK.BYTONAYDURUM,FARK.DBLFARK,FARK.TXTSAYIMGRUPNO 
 FROM TBLSBSAYIMFARKONAY FARK INNER JOIN 
 (SELECT MAX(BAS.LNGKOD) LNGBASLIKKOD,BAS.TXTSAYIMGRUPNO,DET.TXTPALETNO,DET.TXTSERINO,DET.TXTPO,DET.TXTPOLINE,DET.TXTBATCHNO FROM TBLSBSAYIMBELGEDETAY DET INNER JOIN 
 TBLSBSAYIMBELGEBASLIK BAS ON DET.LNGBASLIKKOD=BAS.LNGKOD
 GROUP BY BAS.LNGKOD,BAS.TXTSAYIMGRUPNO,DET.TXTPALETNO,DET.TXTSERINO,DET.TXTPO,DET.TXTPOLINE,DET.TXTBATCHNO  
 ) AS TBL2 ON 1=1 AND 
 ISNULL(FARK.TXTPALETNO COLLATE Turkish_CI_AS,'''')=ISNULL(TBL2.TXTPALETNO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(FARK.TXTBATCHNO COLLATE Turkish_CI_AS,'''')=ISNULL(TBL2.TXTBATCHNO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(FARK.TXTSERINO COLLATE Turkish_CI_AS,'''')=ISNULL(TBL2.TXTSERINO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(FARK.TXTPO COLLATE Turkish_CI_AS,'''')=ISNULL(TBL2.TXTPO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(FARK.TXTPOLINE COLLATE Turkish_CI_AS,'''')=ISNULL(TBL2.TXTPOLINE COLLATE Turkish_CI_AS,'''')
 WHERE FARK.TXTSAYIMGRUPNO=TBL2.TXTSAYIMGRUPNO AND FARK.TXTPALETNO= ISNULL(TBL2.TXTPALETNO COLLATE Turkish_CI_AS,'''')
 ) 
 AS SAY ON  ISNULL(PAL.TXTPALETNO COLLATE Turkish_CI_AS,'''')=ISNULL(PAL.TXTPALETNO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(SD.TXTBATCHNO COLLATE Turkish_CI_AS,'''')=ISNULL(SAY.TXTBATCHNO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(SD.TXTSERINO COLLATE Turkish_CI_AS,'''')=ISNULL(SAY.TXTSERINO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(SD.TXTPO COLLATE Turkish_CI_AS,'''')=ISNULL(SAY.TXTPO COLLATE Turkish_CI_AS,'''') 
 AND ISNULL(SD.TXTPOLINE COLLATE Turkish_CI_AS,'''')=ISNULL(SAY.TXTPOLINE COLLATE Turkish_CI_AS,'''')'
SET @WHERE+=' AND (((SAY.BYTONAYDURUM<>0 AND SAY.BYTONAYDURUM<>3 AND SAY.BYTONAYDURUM IS NOT NULL) OR (SAY.DBLFARK=0 OR SAY.DBLSAYILANMIKTAR=-1) ) OR SAY.DBLFARK IS NULL)   '
 END

PRINT('@FIFOEZILSIN') 
PRINT(@FIFOEZILSIN)            
IF @FIFOEZILSIN ='E'               
BEGIN              
 IF @LNGMUSTERIKOD IS NOT NULL               
 BEGIN              
   IF @LNGREZERVEMUSTERIKOD IS NOT NULL AND @LNGREZERVEMUSTERIKOD<>0 
   BEGIN
   SET @WHERE+=' AND 1=2 ' 
   SET @SQL2+=' AND 1=2 '
   PRINT('@FIFOEZILSIN where') 
   END
   ELSE SET @wHERE+=' AND LNGMUSTERIKOD IN (' + CONVERT(NVARCHAR(50),@LNGMUSTERIKOD) +')'            
 END              
 ELSE IF @LNGMUSTERIKOD IS NULL 
 BEGIN
 SET @WHERE+= ' AND LNGMUSTERIKOD IS NULL '  
 SET @SQL2+= ' AND LNGMUSTERIKOD IS NULL ' 
 END
END              
Print(@LNGRAFOMRUSURESI)            
Print(@TXTKONTROLSAHASI)            
Print(@LNGYUZDEDEGER)            
IF @LNGYUZDEDEGER>0 AND @LNGRAFOMRUSURESI>0 -- Raf Ömrü Kontrolü                
BEGIN                
  IF @TXTKONTROLSAHASI='TRHSONKULLANMATARIHI'  
  BEGIN
  SET @WHERE+= ' AND CONVERT(DECIMAL,(DateDiff(day,dateadd(dd,-' + CONVERT(NVARCHAR(50),@LNGRAFOMRUSURESI) + ',SD.' + @TXTKONTROLSAHASI + '),GETDATE())))/' + CONVERT(NVARCHAR(50),@LNGRAFOMRUSURESI) + '*100 <= ' + CONVERT(NVARCHAR(50),@LNGYUZDEDEGER)           
  SET @SQL2+= ' AND CONVERT(DECIMAL,(DateDiff(day,dateadd(dd,-' + CONVERT(NVARCHAR(50),@LNGRAFOMRUSURESI) + ',SD.' + @TXTKONTROLSAHASI + '),GETDATE())))/' + CONVERT(NVARCHAR(50),@LNGRAFOMRUSURESI) + '*100 <= ' + CONVERT(NVARCHAR(50),@LNGYUZDEDEGER)           
  END
    
     
  ELSE IF @TXTKONTROLSAHASI='TRHURETIMTARIHI'
  BEGIN
   SET @WHERE+= ' AND CONVERT(DECIMAL,(DateDiff(day,SD.' + @TXTKONTROLSAHASI + ',GETDATE())))/' + CONVERT(NVARCHAR(50),@LNGRAFOMRUSURESI) + '*100 <= ' + CONVERT(NVARCHAR(50),@LNGYUZDEDEGER) 
   SET @SQL2+= ' AND CONVERT(DECIMAL,(DateDiff(day,SD.' + @TXTKONTROLSAHASI + ',GETDATE())))/' + CONVERT(NVARCHAR(50),@LNGRAFOMRUSURESI) + '*100 <= ' + CONVERT(NVARCHAR(50),@LNGYUZDEDEGER) 

  END
