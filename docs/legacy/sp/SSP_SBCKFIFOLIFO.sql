AS    
 --BEGIN TRANSACTION
DECLARE @SQL NVARCHAR(4000)    
DECLARE @SQL2 NVARCHAR(4000)
DECLARE @OPERATOR NVARCHAR(1)   
DECLARE @WHERE NVARCHAR(4000)
DECLARE @SQLSAYIMFARK NVARCHAR(4000)=''
DECLARE @RESULT NVARCHAR(4000)
DECLARE @BYTONAYLISAYIMKONTROLUYAPILSIN TINYINT
DECLARE @KONTROLSAHASIKRITER NVARCHAR(500)
DECLARE @GUN INT



--Sayimda Onayli Sayim Kontrolü Yapilacak mi ?
SELECT @BYTONAYLISAYIMKONTROLUYAPILSIN=BYTONAYLISAYIMKONTROLU FROM TBLSBOPERASYONTIPI WHERE LNGKOD=@LNGOPERASYONTIPI

PRINT 'ONAYLISAYIMPARAMETRESI = '+Convert(nvarchar,@BYTONAYLISAYIMKONTROLUYAPILSIN)

